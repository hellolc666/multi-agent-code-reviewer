"""Shared review-runner.

Both the CLI (``reviewer.cli``) and the HTTP API (``reviewer.api``) call into
``run_review`` so end-to-end behavior is identical between the two entrypoints.

Owns:
    - PR fetch (via the async context manager from ``github_client``).
    - State seeding (changed_files, repo_path, trace_id, started_at).
    - Planner override when ``only`` is set.
    - Graph invocation.
    - Optional PR-comment posting.
"""

from __future__ import annotations

import asyncio
import logging
import uuid
from datetime import UTC, datetime
from typing import Any

from reviewer.graph.builder import build_review_graph
from reviewer.graph.state import AGENT_NODE_TO_LABEL, ReviewState
from reviewer.observability import langsmith_setup
from reviewer.tools.github_client import fetch_pr, parse_pr_url

log = logging.getLogger(__name__)

LABEL_TO_NODE = {label: node for node, label in AGENT_NODE_TO_LABEL.items()}


def _utcnow_iso() -> str:
    return datetime.now(tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _resolve_only(only: list[str] | None) -> list[str] | None:
    """Convert short labels to graph node names. ``None`` = let planner decide."""
    if not only:
        return None
    nodes: list[str] = []
    for token in only:
        token = token.strip()
        if not token:
            continue
        if token in LABEL_TO_NODE:
            node = LABEL_TO_NODE[token]
        elif token in AGENT_NODE_TO_LABEL:
            node = token  # already a node name
        else:
            log.warning("ignoring unknown agent in --only: %r", token)
            continue
        if node not in nodes:
            nodes.append(node)
    return nodes


# URL of the reviewer project, used in the comment footer to make the bot
# nature of the comment unambiguous (the comment is posted using the PR
# author's token, so GitHub will show *them* as the commenter — the body has
# to disclose the automated source explicitly).
REVIEWER_PROJECT_URL = "https://github.com/OmkumarSolanki/multi-agent-code-reviewer"


def _format_comment_body(report: dict[str, Any]) -> str:
    """Render a Markdown summary suitable for a single PR comment.

    Includes an unambiguous bot-attribution header AND footer. GitHub will
    attribute the comment to whichever account owns the token used to post
    it, so the body must make it clear the *content* was generated by an
    automated reviewer, not written by that user.
    """
    findings = report.get("findings", [])
    summary = report.get("summary", "")
    trace_id = report.get("trace_id", "")
    pr_author = (report.get("pr_author") or "").strip()
    by_severity: dict[str, list[dict]] = {}
    for f in findings:
        by_severity.setdefault(f.get("severity", "info"), []).append(f)

    # The first line is the unmistakable bot-attribution warning. GitHub will
    # still show whichever account's token posted the comment (typically the
    # PR author), so we call that out explicitly with an @mention to make it
    # obvious to anyone scanning the PR thread.
    if pr_author:
        attribution_warning = f"## ⚠️ This is an automated comment — NOT written by @{pr_author}"
    else:
        attribution_warning = "## ⚠️ This is an automated comment — NOT written by the PR author"

    lines = [
        attribution_warning,
        "",
        (
            f"🤖 Generated by [multi-agent-code-reviewer]({REVIEWER_PROJECT_URL}), "
            "an AI-assisted code review tool. The account shown as the commenter "
            "only owns the API token used to post it — they did not write any of "
            "the analysis below. Findings come from static analysis tools "
            "(Semgrep, Ruff, Python AST) plus an LLM and should be reviewed by a "
            "human before action."
        ),
        "",
        "---",
        "",
        "### Summary",
        "",
        summary or "_(no summary generated)_",
        "",
        f"- **Files changed:** {report.get('files_changed', 0)}",
        f"- **Findings:** {len(findings)}",
        f"- **Agents succeeded:** {', '.join(report.get('agents_succeeded', [])) or '—'}",
    ]
    failed = report.get("agents_failed", [])
    if failed:
        lines.append(
            "- **Agents failed:** "
            + ", ".join(f"{rec.get('agent')} ({rec.get('error')})" for rec in failed)
        )
    lines.append("")

    for sev in ("critical", "high", "medium", "low", "info"):
        items = by_severity.get(sev, [])
        if not items:
            continue
        lines.append(f"### {sev.upper()} ({len(items)})")
        for f in items:
            loc = f.get("file_path", "")
            line = f.get("line_start")
            loc_md = f"`{loc}:{line}`" if line is not None else f"`{loc}`"
            lines.append(f"- {loc_md} — **{f.get('title', '')}**")
            if f.get("explanation"):
                lines.append(f"  - {f['explanation']}")
            if f.get("suggestion"):
                lines.append(f"  - 💡 {f['suggestion']}")
        lines.append("")

    # Traceability footer — duplicates the disclaimer for readers who scrolled
    # past the long findings list and might land here first.
    lines.extend(
        [
            "---",
            "",
            (
                f"_Automated review by [multi-agent-code-reviewer]({REVIEWER_PROJECT_URL}). "
                f"Trace ID: `{trace_id or 'n/a'}`._"
            ),
        ]
    )

    return "\n".join(lines).rstrip() + "\n"


def _post_pr_comment(pr_url: str, github_token: str, body: str) -> None:
    """Post a single issue-comment back to the PR via PyGithub. Synchronous."""
    from github import Github

    owner, repo, number = parse_pr_url(pr_url)
    gh = Github(github_token)
    pr = gh.get_repo(f"{owner}/{repo}").get_pull(number)
    pr.create_issue_comment(body)


def _forced_planner(nodes: list[str]):
    async def _node(state: ReviewState) -> dict[str, Any]:  # noqa: ARG001
        return {"agents_to_run": nodes}

    return _node


async def _execute_review(
    value,
    diff,
    root,
    *,
    pr_url="",
    metadata=None,
    only=None,
    live=False,
    tracing=None,
    context_tools=True,
):
    """The only graph execution path, shared by GitHub and local diff inputs."""
    from reviewer.offline import MockLLM, model_override, offline_mode, review_active
    from reviewer.tools.diff_input import changed_sources

    sources, errors = changed_sources(value, root)
    metadata = {"started_at": _utcnow_iso(), **(metadata or {})}
    seed: ReviewState = {
        "pr_url": pr_url,
        "pr_metadata": metadata,
        "pr_diff": diff,
        "changed_files": sources,
        "test_files": [],
        "repo_path": str(root),
        "trace_id": str(uuid.uuid4()),
        "review_input": value.model_dump(mode="json"),
        "context_tools_enabled": context_tools,
        "source_errors": errors,
        "execution_mode": "live" if live else "mock",
    }
    forced = _resolve_only(only)
    graph = (
        build_review_graph(planner_node=_forced_planner(forced))
        if forced is not None
        else build_review_graph()
    )
    config = {"run_name": "pr_review"}
    if tracing and tracing.get("enabled"):
        config.update(tags=tracing.get("tags", []), metadata=tracing.get("metadata", {}))
    model_token = model_override.set(None if live else MockLLM())
    offline_token = offline_mode.set(not live)
    active_token = review_active.set(True)
    try:
        result = await graph.ainvoke(seed, config=config)
    finally:
        review_active.reset(active_token)
        offline_mode.reset(offline_token)
        model_override.reset(model_token)
    report = result.get("final_report") or {}
    return report


async def run_review(
    pr_url: str,
    *,
    github_token: str | None = None,
    only: list[str] | None = None,
    post_comments: bool = False,
    live: bool = False,
) -> dict[str, Any]:
    """Fetch GitHub input, execute the common pipeline; publishing is explicit."""
    from reviewer.tools.diff_input import make_input

    async with fetch_pr(pr_url, github_token=github_token) as bundle:
        fallback = [{"path": f.path, "change_type": f.change_type} for f in bundle.changed_files]
        value, diff = make_input(
            bundle.pr_diff,
            mode="github",
            head_sha=bundle.metadata.head_sha,
            fallback_files=fallback,
        )
        tracing = (
            langsmith_setup.configure_tracing(
                pr_url=pr_url,
                pr_author=bundle.metadata.author,
                repo_name=f"{bundle.metadata.owner}/{bundle.metadata.repo}",
            )
            if live
            else None
        )
        report = await _execute_review(
            value,
            diff,
            bundle.repo_path,
            pr_url=pr_url,
            only=only,
            live=live,
            metadata={
                "title": bundle.metadata.title,
                "author": bundle.metadata.author,
                "head_sha": bundle.metadata.head_sha,
            },
            tracing=tracing,
        )
    if post_comments and report:
        if not github_token:
            log.warning("post_comments requested but no github_token; skipping")
        else:
            try:
                await asyncio.to_thread(
                    _post_pr_comment, pr_url, github_token, _format_comment_body(report)
                )
            except Exception as exc:
                log.error("failed to post PR comment: %s", type(exc).__name__)
    return report


async def run_review_diff(
    diff_path,
    repo_path,
    *,
    output=None,
    only=None,
    live=False,
    context_tools=True,
):
    """Review an explicitly supplied UTF-8 patch against a read-only checkout."""
    from pathlib import Path

    from reviewer.tools.diff_input import make_input

    with Path(diff_path).open("rb") as stream:
        data = stream.read(4 * 1024 * 1024 + 1)
    if len(data) > 4 * 1024 * 1024:
        raise ValueError("diff exceeds 4 MiB input limit")
    value, diff = make_input(data.decode("utf-8"), mode="diff")
    # Hash exactly supplied bytes, including CRLF.
    import hashlib

    value.diff_sha256 = hashlib.sha256(data).hexdigest()
    report = await _execute_review(
        value,
        diff,
        Path(repo_path).resolve(strict=True),
        only=only,
        live=live,
        context_tools=context_tools,
    )
    if output:
        import json

        Path(output).write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    return report
