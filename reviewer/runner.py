"""Shared review-runner.

Both the CLI (``reviewer.cli``) and the HTTP API (``reviewer.api``) call into
``run_review`` so end-to-end behavior is identical between the two entrypoints.

Owns:
    - PR fetch (via the async context manager from ``github_client``).
    - State seeding (changed_files, repo_path, trace_id, started_at).
    - Planner override when ``only`` is set.
    - Graph invocation.
    - Optional PR-comment posting.
"""

from __future__ import annotations

import asyncio
import logging
from datetime import UTC, datetime
from typing import Any

from reviewer.graph.builder import build_review_graph
from reviewer.graph.state import AGENT_NODE_TO_LABEL, ReviewState
from reviewer.observability import langsmith_setup
from reviewer.tools.github_client import fetch_pr

log = logging.getLogger(__name__)

LABEL_TO_NODE = {label: node for node, label in AGENT_NODE_TO_LABEL.items()}


def _utcnow_iso() -> str:
    return datetime.now(tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _resolve_only(only: list[str] | None) -> list[str] | None:
    """Convert short labels to graph node names. ``None`` = let planner decide."""
    if not only:
        return None
    nodes: list[str] = []
    for token in only:
        token = token.strip()
        if not token:
            continue
        if token in LABEL_TO_NODE:
            node = LABEL_TO_NODE[token]
        elif token in AGENT_NODE_TO_LABEL:
            node = token  # already a node name
        else:
            log.warning("ignoring unknown agent in --only: %r", token)
            continue
        if node not in nodes:
            nodes.append(node)
    return nodes


# URL of the reviewer project, used in the comment footer to make the bot
# nature of the comment unambiguous (the comment is posted using the PR
# author's token, so GitHub will show *them* as the commenter — the body has
# to disclose the automated source explicitly).
REVIEWER_PROJECT_URL = "https://github.com/OmkumarSolanki/multi-agent-code-reviewer"


def _format_comment_body(report: dict[str, Any]) -> str:
    """Render a Markdown summary suitable for a single PR comment.

    Includes an unambiguous bot-attribution header AND footer. GitHub will
    attribute the comment to whichever account owns the token used to post
    it, so the body must make it clear the *content* was generated by an
    automated reviewer, not written by that user.
    """
    findings = report.get("findings", [])
    summary = report.get("summary", "")
    trace_id = report.get("trace_id", "")
    pr_author = (report.get("pr_author") or "").strip()
    by_severity: dict[str, list[dict]] = {}
    for f in findings:
        by_severity.setdefault(f.get("severity", "info"), []).append(f)

    # The first line is the unmistakable bot-attribution warning. GitHub will
    # still show whichever account's token posted the comment (typically the
    # PR author), so we call that out explicitly with an @mention to make it
    # obvious to anyone scanning the PR thread.
    if pr_author:
        attribution_warning = f"## ⚠️ This is an automated comment — NOT written by @{pr_author}"
    else:
        attribution_warning = "## ⚠️ This is an automated comment — NOT written by the PR author"

    lines = [
        attribution_warning,
        "",
        (
            f"🤖 Generated by [multi-agent-code-reviewer]({REVIEWER_PROJECT_URL}), "
            "an AI-assisted code review tool. The account shown as the commenter "
            "only owns the API token used to post it — they did not write any of "
            "the analysis below. Findings come from static analysis tools "
            "(Semgrep, Ruff, Python AST) plus an LLM and should be reviewed by a "
            "human before action."
        ),
        "",
        "---",
        "",
        "### Summary",
        "",
        summary or "_(no summary generated)_",
        "",
        f"- **Files changed:** {report.get('files_changed', 0)}",
        f"- **Findings:** {len(findings)}",
        f"- **Agents succeeded:** {', '.join(report.get('agents_succeeded', [])) or '—'}",
    ]
    failed = report.get("agents_failed", [])
    if failed:
        lines.append(
            "- **Agents failed:** "
            + ", ".join(f"{rec.get('agent')} ({rec.get('error')})" for rec in failed)
        )
    lines.append("")

    for sev in ("critical", "high", "medium", "low", "info"):
        items = by_severity.get(sev, [])
        if not items:
            continue
        lines.append(f"### {sev.upper()} ({len(items)})")
        for f in items:
            loc = f.get("file_path", "")
            line = f.get("line_start")
            loc_md = f"`{loc}:{line}`" if line is not None else f"`{loc}`"
            lines.append(f"- {loc_md} — **{f.get('title', '')}**")
            if f.get("explanation"):
                lines.append(f"  - {f['explanation']}")
            if f.get("suggestion"):
                lines.append(f"  - 💡 {f['suggestion']}")
        lines.append("")

    # Traceability footer — duplicates the disclaimer for readers who scrolled
    # past the long findings list and might land here first.
    lines.extend(
        [
            "---",
            "",
            (
                f"_Automated review by [multi-agent-code-reviewer]({REVIEWER_PROJECT_URL}). "
                f"Trace ID: `{trace_id or 'n/a'}`._"
            ),
        ]
    )

    return "\n".join(lines).rstrip() + "\n"


def _post_pr_comment(pr_url, github_token, body, **kwargs):
    """Compatibility hook; all writes use the shared checked publisher."""
    from reviewer.publication import post_comment

    return post_comment(pr_url, github_token, body, **kwargs)


def _forced_planner(nodes: list[str]):
    async def _node(state: ReviewState) -> dict[str, Any]:  # noqa: ARG001
        maximum = state.get("review_options", {}).get("max_reviewers", 5)
        selected = nodes[:maximum]
        return {
            "agents_to_run": selected,
            "review_plan": {
                "selected_agents": [AGENT_NODE_TO_LABEL[n] for n in selected],
                "routing_reasons": {
                    AGENT_NODE_TO_LABEL[n]: "Explicit --only override" for n in selected
                },
                "budget": {"omitted_agents": [AGENT_NODE_TO_LABEL[n] for n in nodes[maximum:]]},
            },
        }

    return _node


def _interrupted_report(runtime, exc):
    from reviewer.models.report import ReviewReport

    runtime.fail("pipeline", exc)
    runtime.exhausted = runtime.exhausted or isinstance(exc, TimeoutError)
    saved = runtime.snapshot
    metadata = saved.get("pr_metadata", {})
    value = saved.get("review_input", {})
    successes = saved.get("agents_succeeded", [])
    missing = [
        AGENT_NODE_TO_LABEL.get(n, n)
        for n in saved.get("agents_to_run", [])
        if AGENT_NODE_TO_LABEL.get(n, n) not in successes
    ]
    raw = saved.get("findings", [])
    return ReviewReport(
        pr_url=saved.get("pr_url", ""),
        pr_title=metadata.get("title", ""),
        pr_author=metadata.get("author", ""),
        review_started_at=metadata.get("started_at", _utcnow_iso()),
        review_completed_at=_utcnow_iso(),
        duration_seconds=runtime.budget.total_seconds - runtime.remaining(),
        files_changed=len(saved.get("changed_files", [])),
        findings=[],
        raw_findings=raw,
        verified_findings=[
            {
                "finding": f.model_dump(mode="json"),
                "status": "uncertain",
                "reason": "pipeline_interrupted",
                "can_comment": False,
            }
            for f in raw
        ],
        summary="Review interrupted; partial evidence preserved; verification incomplete.",
        agents_succeeded=successes,
        agents_failed=[{"agent": a, "error": type(exc).__name__} for a in missing],
        trace_id=runtime.run_id,
        execution_mode=saved.get("execution_mode", "mock"),
        input_mode=value.get("mode", "github"),
        diff_sha256=value.get("diff_sha256"),
        head_sha=value.get("head_sha"),
        reviewed_files=[f["path"] for f in value.get("files", [])],
        coverage=value.get("coverage", {}),
        source_errors=saved.get("source_errors", []),
        review_plan=saved.get("review_plan", {}),
        verification_incomplete=True,
    ).model_dump(mode="json")


def _with_deadline(fn):
    from functools import wraps

    @wraps(fn)
    async def wrapped(*args, **kwargs):
        from reviewer.reliability.harness import ReviewBudget, RunHarness

        options = kwargs.get("options") or {}
        runtime = RunHarness(ReviewBudget.model_validate(options.get("budget", {})))
        runtime.snapshot = {
            "pr_url": str(args[0]) if fn.__name__ == "run_review" and args else "",
            "pr_metadata": {"started_at": _utcnow_iso()},
            "execution_mode": "live" if kwargs.get("live") else "mock",
        }
        try:
            async with asyncio.timeout(runtime.remaining()):
                return await fn(*args, **kwargs, _runtime=runtime)
        except TimeoutError as exc:
            return _finish_report(_interrupted_report(runtime, exc), runtime, options)

    return wrapped


async def _execute_review(
    value,
    diff,
    root,
    *,
    pr_url="",
    metadata=None,
    only=None,
    live=False,
    tracing=None,
    context_tools=True,
    options=None,
    runtime=None,
    model_client=None,
):
    """The sole graph execution path, with per-run isolation and recovery."""
    from langsmith import tracing_context

    from reviewer.offline import MockLLM, model_override, offline_mode, review_active
    from reviewer.reliability.harness import ReviewBudget, RunHarness, current_run
    from reviewer.tools.diff_input import changed_sources

    options = dict(options or {})
    budget = ReviewBudget.model_validate(options.get("budget", {}))
    runtime = runtime or RunHarness(budget)
    options["max_reviewers"] = min(
        options.get("max_reviewers", budget.max_reviewers), budget.max_reviewers
    )
    sources, errors = changed_sources(value, root)
    metadata = {"started_at": _utcnow_iso(), **(metadata or {})}
    seed: ReviewState = {
        "pr_url": pr_url,
        "pr_metadata": metadata,
        "pr_diff": diff,
        "changed_files": sources,
        "test_files": [],
        "repo_path": str(root),
        "trace_id": runtime.run_id,
        "review_input": value.model_dump(mode="json"),
        "context_tools_enabled": context_tools,
        "source_errors": errors,
        "execution_mode": "live" if live else "mock",
        "review_options": options,
    }
    runtime.snapshot = dict(seed)
    forced = _resolve_only(only)
    graph = (
        build_review_graph(planner_node=_forced_planner(forced))
        if forced is not None
        else build_review_graph()
    )
    config = {"run_name": "pr_review"}
    if tracing and tracing.get("enabled"):
        config.update(tags=tracing.get("tags", []), metadata=tracing.get("metadata", {}))
    if live and model_client is not None:
        raise ValueError("model_client injection is reserved for offline tests and demos")
    model_token = model_override.set(None if live else model_client or MockLLM())
    offline_token = offline_mode.set(not live)
    active_token = review_active.set(True)
    runtime_token = current_run.set(runtime)
    try:
        # Use our sanitized trace rather than exporting source-bearing LangChain traces.
        with tracing_context(enabled=False):
            async with asyncio.timeout(runtime.remaining()):
                result = await graph.ainvoke(seed, config=config)
        report = result.get("final_report") or {}
    except Exception as exc:
        report = _interrupted_report(runtime, exc)
    finally:
        current_run.reset(runtime_token)
        review_active.reset(active_token)
        offline_mode.reset(offline_token)
        model_override.reset(model_token)
    return _finish_report(report, runtime, options)


def _finish_report(report, runtime, options):
    if not report:
        return report
    failures = list(report.get("agents_failed", []))
    for failure in runtime.failures:
        if failure not in failures:
            failures.append(failure)
    report["agents_failed"] = failures
    selected = runtime.snapshot.get("agents_to_run", [])
    incomplete = (
        failures
        or report.get("source_errors")
        or report.get("verification_incomplete")
        or report.get("coverage", {}).get("omitted")
        or report.get("budget_events")
        or report.get("planner_errors")
        or any(not e.get("ok", True) for e in report.get("tool_evidence", []))
        or runtime.exhausted
        or report.get("review_plan", {}).get("budget", {}).get("omitted_agents")
    )
    if not selected and not failures and not report.get("agents_succeeded"):
        status = "skipped"
    elif incomplete:
        status = "partial" if report.get("agents_succeeded") else "failed"
    else:
        status = "completed"
    report.update(
        status=status,
        run_id=runtime.run_id,
        review_version="2.0.0",
        prompt_version="review-v2.0",
        budget=runtime.budget.model_dump(),
        usage=runtime.summary(options),
        trace=runtime.events,
        unreviewed_dimensions=sorted(
            {f["agent"] for f in failures}
            | set(report.get("review_plan", {}).get("budget", {}).get("omitted_agents", []))
        ),
        publication={"status": "dry_run"},
    )
    return report


@_with_deadline
async def run_review(
    pr_url: str,
    *,
    github_token: str | None = None,
    only: list[str] | None = None,
    post_comments: bool = False,
    live: bool = False,
    options: dict | None = None,
    _runtime=None,
) -> dict[str, Any]:
    """Fetch GitHub input, execute the common pipeline; publishing is explicit."""
    from reviewer.tools.diff_input import make_input

    async with fetch_pr(pr_url, github_token=github_token) as bundle:
        fallback = [{"path": f.path, "change_type": f.change_type} for f in bundle.changed_files]
        value, diff = make_input(
            bundle.pr_diff,
            mode="github",
            head_sha=bundle.metadata.head_sha,
            fallback_files=fallback,
        )
        tracing = (
            langsmith_setup.configure_tracing(
                pr_url=pr_url,
                pr_author=bundle.metadata.author,
                repo_name=f"{bundle.metadata.owner}/{bundle.metadata.repo}",
            )
            if live
            else None
        )
        report = await _execute_review(
            value,
            diff,
            bundle.repo_path,
            pr_url=pr_url,
            only=only,
            live=live,
            metadata={
                "title": bundle.metadata.title,
                "author": bundle.metadata.author,
                "head_sha": bundle.metadata.head_sha,
            },
            tracing=tracing,
            options=options,
            runtime=_runtime,
        )
    if post_comments and report:
        from reviewer.publication import publish_report

        try:
            report["publication"] = await asyncio.to_thread(
                publish_report,
                report,
                github_token,
                post_comments=True,
                poster=_post_pr_comment,
            )
        except Exception as exc:
            report["publication"] = {"status": "blocked_or_failed", "error": type(exc).__name__}
            log.error("PR publication blocked/failed: %s", type(exc).__name__)
    return report


@_with_deadline
async def run_review_diff(
    diff_path,
    repo_path,
    *,
    output=None,
    only=None,
    live=False,
    context_tools=True,
    options=None,
    model_client=None,
    _runtime=None,
):
    """Review an explicitly supplied UTF-8 patch against a read-only checkout."""
    from pathlib import Path

    from reviewer.tools.diff_input import make_input

    with Path(diff_path).open("rb") as stream:
        data = stream.read(4 * 1024 * 1024 + 1)
    if len(data) > 4 * 1024 * 1024:
        raise ValueError("diff exceeds 4 MiB input limit")
    value, diff = make_input(data.decode("utf-8"), mode="diff")
    # Hash exactly supplied bytes, including CRLF.
    import hashlib

    value.diff_sha256 = hashlib.sha256(data).hexdigest()
    report = await _execute_review(
        value,
        diff,
        Path(repo_path).resolve(strict=True),
        only=only,
        live=live,
        context_tools=context_tools,
        options=options,
        runtime=_runtime,
        model_client=model_client,
    )
    if output:
        import json

        Path(output).write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    return report
